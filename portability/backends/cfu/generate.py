"""Generate a NEORV32-CFU-compatible VHDL module from XSIL instructions.

Ports match ``neorv32_cpu_alu_cfu`` (start_i / inst_i / rs1_i / rs2_i /
result_o / valid_o) plus adapter port ``rsd_i`` for rd-as-source.
Datapath expressions are compiled from the semantic IR.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable, List, Sequence

from xsil_sem.schema import Instruction
from xsil_sem.vhdl_expr import to_vhdl


def _operand_env(instr: Instruction) -> dict[str, str]:
    env = {}
    for role in instr.inputs:
        if role == "rd":
            env[role] = "rsd_q"
        elif role == "rs1":
            env[role] = "rs1_q"
        elif role == "rs2":
            env[role] = "rs2_q"
        else:
            raise ValueError(f"CFU MVP cannot bind operand role {role!r}")
    return env


def generate_entity(instructions: Sequence[Instruction], entity: str = "xsil_cfu") -> str:
    if not instructions:
        raise ValueError("need at least one instruction")

    match_signals = "\n  ".join(
        f"signal match_{i.name} : std_ulogic;" for i in instructions
    )
    match_assigns = "\n  ".join(
        f"match_{i.name} <= start_i when "
        f"((inst_i and x\"{i.encoding.mask:08x}\") = x\"{i.encoding.match:08x}\") "
        f"else '0';"
        for i in instructions
    )
    match_any = " or ".join(f"(match_{i.name} = '1')" for i in instructions)

    # Latched-match flags for datapath mux after start pulse is gone.
    match_q = "\n  ".join(f"signal match_{i.name}_q : std_ulogic := '0';" for i in instructions)
    capture_matches = "\n        ".join(
        f"match_{i.name}_q <= match_{i.name};" for i in instructions
    )
    clear_matches = "\n        ".join(
        f"match_{i.name}_q <= '0';" for i in instructions
    )

    result_cases: List[str] = []
    for instr in instructions:
        env = _operand_env(instr)
        expr = to_vhdl(instr.output_expr, env, instr.xlen)
        result_cases.append(
            f"    if match_{instr.name}_q = '1' then\n"
            f"      result_d := {expr};\n"
            f"    end if;"
        )
    # Priority: first match wins; mutually exclusive encodings in practice.
    result_block = "\n".join(result_cases)

    return f"""-- -----------------------------------------------------------------------------
-- AUTO-GENERATED by ExtenSilica portability backend (experimental).
-- Do not edit by hand — regenerate from the XSIL semantic descriptions.
-- CFU handshake matches NEORV32 neorv32_cpu_alu_cfu; datapath = compiled IR.
-- Extra port rsd_i: adapter for rd-as-source (not in stock CFU).
-- -----------------------------------------------------------------------------
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity {entity} is
  port (
    clk_i    : in  std_ulogic;
    rstn_i   : in  std_ulogic;
    start_i  : in  std_ulogic;
    inst_i   : in  std_ulogic_vector(31 downto 0);
    rs1_i    : in  std_ulogic_vector(31 downto 0);
    rs2_i    : in  std_ulogic_vector(31 downto 0);
    rsd_i    : in  std_ulogic_vector(31 downto 0);  -- adapter: current rd value
    result_o : out std_ulogic_vector(31 downto 0);
    valid_o  : out std_ulogic
  );
end entity;

architecture rtl of {entity} is
  function xsil_rotl(a : std_ulogic_vector(31 downto 0);
                     b : std_ulogic_vector(31 downto 0)) return std_ulogic_vector is
    variable s : integer;
    variable x : std_ulogic_vector(31 downto 0);
  begin
    s := to_integer(unsigned(b(4 downto 0)));
    if s = 0 then
      return a;
    else
      x := a(31-s downto 0) & a(31 downto 32-s);
      return x;
    end if;
  end function;

  function xsil_rotr(a : std_ulogic_vector(31 downto 0);
                     b : std_ulogic_vector(31 downto 0)) return std_ulogic_vector is
    variable s : integer;
    variable x : std_ulogic_vector(31 downto 0);
  begin
    s := to_integer(unsigned(b(4 downto 0)));
    if s = 0 then
      return a;
    else
      x := a(s-1 downto 0) & a(31 downto s);
      return x;
    end if;
  end function;

  function xsil_clz(a : std_ulogic_vector(31 downto 0)) return std_ulogic_vector is
    variable r : integer := 32;
  begin
    for i in 31 downto 0 loop
      if a(i) = '1' then
        r := 31 - i;
        exit;
      end if;
    end loop;
    return std_ulogic_vector(to_unsigned(r, 32));
  end function;

  {match_signals}
  {match_q}
  signal match_any : boolean;
  signal rs1_q, rs2_q, rsd_q : std_ulogic_vector(31 downto 0) := (others => '0');
  signal done : std_ulogic_vector(1 downto 0) := (others => '0');
  signal result_q : std_ulogic_vector(31 downto 0) := (others => '0');
begin
  {match_assigns}
  match_any <= {match_any};

  process(rstn_i, clk_i)
    variable result_d : std_ulogic_vector(31 downto 0);
  begin
    if rstn_i = '0' then
      done <= (others => '0');
      rs1_q <= (others => '0');
      rs2_q <= (others => '0');
      rsd_q <= (others => '0');
      result_q <= (others => '0');
      {clear_matches}
    elsif rising_edge(clk_i) then
      done(0) <= '0';
      done(1) <= done(0);

      if match_any then
        {capture_matches}
        rs1_q <= rs1_i;
        rs2_q <= rs2_i;
        rsd_q <= rsd_i;
        done(0) <= '1';
      end if;

      if done(0) = '1' then
        result_d := (others => '0');
{result_block}
        result_q <= result_d;
      end if;

      if done(1) = '1' then
        {clear_matches}
      end if;
    end if;
  end process;

  result_o <= result_q;
  valid_o  <= done(1);
end architecture;
"""


def write_entity(path: Path, instructions: Iterable[Instruction], entity: str = "xsil_cfu") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_entity(list(instructions), entity=entity), encoding="utf-8")
    return path
