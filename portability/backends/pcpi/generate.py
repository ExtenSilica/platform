"""Generate a PicoRV32 PCPI coprocessor Verilog module from XSIL instructions.

Datapath expressions are compiled from the semantic IR. The handshake FSM is the
shared PCPI protocol (wait / ready / wr), not instruction-specific logic.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable, List, Sequence

from xsil_sem.schema import Instruction
from xsil_sem.verilog_expr import to_verilog


def _operand_env(instr: Instruction) -> dict[str, str]:
    env = {}
    for role in instr.inputs:
        if role == "rd":
            env[role] = "rsd_q"
        elif role == "rs1":
            env[role] = "rs1_q"
        elif role == "rs2":
            env[role] = "rs2_q"
        else:
            raise ValueError(f"PCPI MVP cannot bind operand role {role!r}")
    return env


def generate_module(instructions: Sequence[Instruction], module: str = "xsil_pcpi") -> str:
    if not instructions:
        raise ValueError("need at least one instruction")

    decode_lines: List[str] = []
    result_cases: List[str] = []
    for instr in instructions:
        env = _operand_env(instr)
        expr = to_verilog(instr.output_expr, env, instr.xlen)
        decode_lines.append(
            f"wire match_{instr.name} = pcpi_valid && "
            f"((pcpi_insn & 32'h{instr.encoding.mask:08x}) == 32'h{instr.encoding.match:08x});"
        )
        result_cases.append(f"      match_{instr.name}_q: result_d = {expr};")

    matches_or = " | ".join(f"match_{i.name}" for i in instructions)
    match_q_regs = "\n  ".join(f"reg match_{i.name}_q;" for i in instructions)
    match_q_clear = "\n        ".join(
        f"match_{i.name}_q <= 1'b0;" for i in instructions
    )
    match_q_capture = "\n          ".join(
        f"match_{i.name}_q <= match_{i.name};" for i in instructions
    )

    return f"""// -----------------------------------------------------------------------------
// AUTO-GENERATED by ExtenSilica portability backend (experimental).
// Do not edit by hand — regenerate from the XSIL semantic descriptions.
// Datapath = compiled IR; handshake = shared PCPI wait/ready protocol.
// -----------------------------------------------------------------------------
`timescale 1ns/1ps
module {module} (
  input             clk,
  input             resetn,

  // Standard PicoRV32 PCPI
  input             pcpi_valid,
  input      [31:0] pcpi_insn,
  input      [31:0] pcpi_rs1,
  input      [31:0] pcpi_rs2,
  output reg        pcpi_wr,
  output reg [31:0] pcpi_rd,
  output reg        pcpi_wait,
  output reg        pcpi_ready,

  // Adapter port: current destination-register value (rd-as-source).
  // Stock PicoRV32 does not provide this; RF tap required for full-core use.
  input      [31:0] pcpi_rsd
);

  localparam S_IDLE = 2'd0;
  localparam S_BUSY = 2'd1;
  localparam S_DONE = 2'd2;

  // Shared IR helpers (used when an instruction's expression references them).
  function automatic [31:0] xsil_clz;
    input [31:0] a;
    integer i;
    reg found;
    begin
      xsil_clz = 32'd32;
      found = 1'b0;
      for (i = 31; i >= 0; i = i - 1) begin
        if (!found && a[i]) begin
          xsil_clz = 31 - i;
          found = 1'b1;
        end
      end
    end
  endfunction

  // Combinational decode of the live instruction word.
{chr(10).join('  ' + l for l in decode_lines)}
  wire match_any = {matches_or};

  {match_q_regs}
  reg [31:0] rs1_q, rs2_q, rsd_q;
  reg [31:0] result_d;
  reg [1:0]  state;

  // Datapath: pure function of latched operands (IR-compiled).
  always @* begin
    result_d = 32'd0;
    case (1'b1)
{chr(10).join(result_cases)}
      default: result_d = 32'd0;
    endcase
  end

  always @(posedge clk) begin
    if (!resetn) begin
      state <= S_IDLE;
      pcpi_wait <= 1'b0;
      pcpi_ready <= 1'b0;
      pcpi_wr <= 1'b0;
      pcpi_rd <= 32'd0;
      rs1_q <= 32'd0;
      rs2_q <= 32'd0;
      rsd_q <= 32'd0;
      {match_q_clear}
    end else begin
      // Defaults: ready/wr are single-cycle pulses.
      pcpi_ready <= 1'b0;
      pcpi_wr <= 1'b0;

      case (state)
        S_IDLE: begin
          pcpi_wait <= 1'b0;
          if (match_any) begin
            {match_q_capture}
            rs1_q <= pcpi_rs1;
            rs2_q <= pcpi_rs2;
            rsd_q <= pcpi_rsd;
            pcpi_wait <= 1'b1;   // ack before the 16-cycle illegal timeout
            state <= S_BUSY;
          end
        end

        S_BUSY: begin
          // One compute cycle with stable latched operands.
          pcpi_wait <= 1'b1;
          state <= S_DONE;
        end

        S_DONE: begin
          pcpi_rd <= result_d;
          pcpi_wr <= 1'b1;
          pcpi_ready <= 1'b1;
          pcpi_wait <= 1'b0;
          {match_q_clear}
          state <= S_IDLE;
        end

        default: state <= S_IDLE;
      endcase
    end
  end

endmodule
"""


def write_module(path: Path, instructions: Iterable[Instruction], module: str = "xsil_pcpi") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_module(list(instructions), module=module), encoding="utf-8")
    return path
