"""Generate a CV-X-IF coprocessor Verilog module from XSIL instructions.

MVP subset of OpenHW CV-X-IF (experimental):

- RV32, X_NUM_RS=2 (rs1/rs2), X_ISSUE_REGISTER_SPLIT=0 style
- No compressed interface
- Issue + register driven together by the test BFM
- Commit required before result (spec rule)
- Adapter port ``register_rsd`` for rd-as-source (stock CV-X-IF does not
  forward current rd)

Datapath expressions are compiled from the semantic IR. Handshake FSM is shared.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable, List, Sequence

from xsil_sem.schema import Instruction
from xsil_sem.verilog_expr import to_verilog


def _operand_env(instr: Instruction) -> dict[str, str]:
    env = {}
    for role in instr.inputs:
        if role == "rd":
            env[role] = "rsd_q"
        elif role == "rs1":
            env[role] = "rs1_q"
        elif role == "rs2":
            env[role] = "rs2_q"
        else:
            raise ValueError(f"CV-X-IF MVP cannot bind operand role {role!r}")
    return env


def generate_module(instructions: Sequence[Instruction], module: str = "xsil_cvxif") -> str:
    if not instructions:
        raise ValueError("need at least one instruction")

    decode_lines: List[str] = []
    result_cases: List[str] = []
    for instr in instructions:
        env = _operand_env(instr)
        expr = to_verilog(instr.output_expr, env, instr.xlen)
        decode_lines.append(
            f"wire match_{instr.name} = issue_valid && register_valid && "
            f"(issue_id == register_id) && "
            f"((issue_instr & 32'h{instr.encoding.mask:08x}) == 32'h{instr.encoding.match:08x});"
        )
        result_cases.append(f"      match_{instr.name}_q: result_data_d = {expr};")

    matches_or = " | ".join(f"match_{i.name}" for i in instructions)
    match_q_regs = "\n  ".join(f"reg match_{i.name}_q;" for i in instructions)
    match_q_clear = "\n        ".join(
        f"match_{i.name}_q <= 1'b0;" for i in instructions
    )
    match_q_capture = "\n          ".join(
        f"match_{i.name}_q <= match_{i.name};" for i in instructions
    )

    return f"""// -----------------------------------------------------------------------------
// AUTO-GENERATED by ExtenSilica portability backend (experimental).
// Do not edit by hand — regenerate from the XSIL semantic descriptions.
// Datapath = compiled IR; handshake = CV-X-IF MVP subset (see docs/cvxif-backend.md).
// -----------------------------------------------------------------------------
`timescale 1ns/1ps
module {module} (
  input             clk,
  input             rst_n,

  // Issue interface (CPU → coprocessor request / response)
  input             issue_valid,
  output reg        issue_ready,
  input      [31:0] issue_instr,
  input       [3:0] issue_id,
  input             issue_hartid,
  output reg        issue_accept,
  output reg        issue_writeback,
  output reg  [2:0] issue_register_read,

  // Register interface (operands). SPLIT=0: concurrent with issue in the BFM.
  input             register_valid,
  output reg        register_ready,
  input       [3:0] register_id,
  input             register_hartid,
  input      [31:0] register_rs1,
  input      [31:0] register_rs2,
  input       [1:0] register_rs_valid,

  // Adapter: current destination-register value (rd-as-source).
  // Stock CV-X-IF does not supply this; RF tap required for full-core use.
  input      [31:0] register_rsd,

  // Commit interface (CPU → coprocessor)
  input             commit_valid,
  input       [3:0] commit_id,
  input             commit_hartid,
  input             commit_kill,

  // Result interface (coprocessor → CPU)
  output reg        result_valid,
  input             result_ready,
  output reg  [3:0] result_id,
  output reg        result_hartid,
  output reg [31:0] result_data,
  output reg  [4:0] result_rd,
  output reg        result_we
);

  localparam S_IDLE        = 3'd0;
  localparam S_WAIT_COMMIT = 3'd1;
  localparam S_COMPUTE     = 3'd2;
  localparam S_RESULT      = 3'd3;

  function automatic [31:0] xsil_clz;
    input [31:0] a;
    integer i;
    reg found;
    begin
      xsil_clz = 32'd32;
      found = 1'b0;
      for (i = 31; i >= 0; i = i - 1) begin
        if (!found && a[i]) begin
          xsil_clz = 31 - i;
          found = 1'b1;
        end
      end
    end
  endfunction

{chr(10).join('  ' + l for l in decode_lines)}
  wire match_any = {matches_or};

  {match_q_regs}
  reg [31:0] rs1_q, rs2_q, rsd_q;
  reg [31:0] result_data_d;
  reg  [3:0] id_q;
  reg        hartid_q;
  reg  [4:0] rd_q;
  reg  [2:0] state;

  always @* begin
    result_data_d = 32'd0;
    case (1'b1)
{chr(10).join(result_cases)}
      default: result_data_d = 32'd0;
    endcase
  end

  always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      state <= S_IDLE;
      issue_ready <= 1'b0;
      issue_accept <= 1'b0;
      issue_writeback <= 1'b0;
      issue_register_read <= 3'b000;
      register_ready <= 1'b0;
      result_valid <= 1'b0;
      result_id <= 4'd0;
      result_hartid <= 1'b0;
      result_data <= 32'd0;
      result_rd <= 5'd0;
      result_we <= 1'b0;
      rs1_q <= 32'd0;
      rs2_q <= 32'd0;
      rsd_q <= 32'd0;
      id_q <= 4'd0;
      hartid_q <= 1'b0;
      rd_q <= 5'd0;
      {match_q_clear}
    end else begin
      // Defaults: issue/register responses are single-cycle in IDLE accept path.
      issue_ready <= 1'b0;
      issue_accept <= 1'b0;
      issue_writeback <= 1'b0;
      issue_register_read <= 3'b000;
      register_ready <= 1'b0;

      case (state)
        S_IDLE: begin
          result_valid <= 1'b0;
          result_we <= 1'b0;
          if (issue_valid && register_valid && (issue_id == register_id) &&
              (issue_hartid == register_hartid)) begin
            if (match_any) begin
              // Accept offload; request rs1+rs2. rd comes via adapter port.
              issue_ready <= 1'b1;
              register_ready <= 1'b1;
              issue_accept <= 1'b1;
              issue_writeback <= 1'b1;
              issue_register_read <= 3'b011;
              {match_q_capture}
              rs1_q <= register_rs1;
              rs2_q <= register_rs2;
              rsd_q <= register_rsd;
              id_q <= issue_id;
              hartid_q <= issue_hartid;
              rd_q <= issue_instr[11:7];
              state <= S_WAIT_COMMIT;
            end else begin
              // Reject unrecognized opcode (CPU should raise illegal insn).
              issue_ready <= 1'b1;
              register_ready <= 1'b1;
              issue_accept <= 1'b0;
              issue_writeback <= 1'b0;
              issue_register_read <= 3'b000;
            end
          end
        end

        S_WAIT_COMMIT: begin
          if (commit_valid && (commit_id == id_q) && (commit_hartid == hartid_q)) begin
            if (commit_kill) begin
              {match_q_clear}
              state <= S_IDLE;
            end else begin
              state <= S_COMPUTE;
            end
          end
        end

        S_COMPUTE: begin
          // One compute cycle with stable latched operands.
          state <= S_RESULT;
        end

        S_RESULT: begin
          result_valid <= 1'b1;
          result_id <= id_q;
          result_hartid <= hartid_q;
          result_data <= result_data_d;
          result_rd <= rd_q;
          result_we <= 1'b1;
          if (result_valid && result_ready) begin
            result_valid <= 1'b0;
            result_we <= 1'b0;
            {match_q_clear}
            state <= S_IDLE;
          end
        end

        default: state <= S_IDLE;
      endcase
    end
  end

endmodule
"""


def write_module(path: Path, instructions: Iterable[Instruction], module: str = "xsil_cvxif") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_module(list(instructions), module=module), encoding="utf-8")
    return path
