"""Generate a RoCC-style accelerator Verilog module from XSIL instructions.

MVP subset of the Rocket Custom Coprocessor (RoCC) interface (experimental):

- RV32 datapath (BFM); no TileLink / HellaCache memory port
- Decoupled ``cmd`` / ``resp`` handshakes + ``busy``
- Native operands: ``cmd_rs1``, ``cmd_rs2`` (values on the command channel)
- Adapter port ``cmd_rsd`` for rd-as-source (stock RoCC does not forward
  the current destination register value)
- No persistent custom state, IRQ, or PTW

Datapath expressions are compiled from the semantic IR. Handshake FSM is shared.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable, List, Sequence

from xsil_sem.schema import Instruction
from xsil_sem.verilog_expr import to_verilog


def _operand_env(instr: Instruction) -> dict[str, str]:
    env = {}
    for role in instr.inputs:
        if role == "rd":
            env[role] = "rsd_q"
        elif role == "rs1":
            env[role] = "rs1_q"
        elif role == "rs2":
            env[role] = "rs2_q"
        else:
            raise ValueError(f"RoCC MVP cannot bind operand role {role!r}")
    return env


def generate_module(instructions: Sequence[Instruction], module: str = "xsil_rocc") -> str:
    if not instructions:
        raise ValueError("need at least one instruction")

    decode_lines: List[str] = []
    result_cases: List[str] = []
    for instr in instructions:
        env = _operand_env(instr)
        expr = to_verilog(instr.output_expr, env, instr.xlen)
        decode_lines.append(
            f"wire match_{instr.name} = cmd_valid && "
            f"((cmd_inst & 32'h{instr.encoding.mask:08x}) == 32'h{instr.encoding.match:08x});"
        )
        result_cases.append(f"      match_{instr.name}_q: result_d = {expr};")

    matches_or = " | ".join(f"match_{i.name}" for i in instructions)
    match_q_regs = "\n  ".join(f"reg match_{i.name}_q;" for i in instructions)
    match_q_clear = "\n        ".join(
        f"match_{i.name}_q <= 1'b0;" for i in instructions
    )
    match_q_capture = "\n          ".join(
        f"match_{i.name}_q <= match_{i.name};" for i in instructions
    )

    return f"""// -----------------------------------------------------------------------------
// AUTO-GENERATED by ExtenSilica portability backend (experimental).
// Do not edit by hand — regenerate from the XSIL semantic descriptions.
// Datapath = compiled IR; handshake = RoCC MVP subset (see docs/rocc-backend.md).
// -----------------------------------------------------------------------------
`timescale 1ns/1ps
module {module} (
  input             clk,
  input             rst_n,

  // RoCC command channel (Decoupled)
  input             cmd_valid,
  output reg        cmd_ready,
  input      [31:0] cmd_inst,
  input      [31:0] cmd_rs1,
  input      [31:0] cmd_rs2,

  // Adapter: current destination-register value (rd-as-source).
  // Stock RoCC only forwards rs1/rs2 values when xs1/xs2 are set.
  input      [31:0] cmd_rsd,

  // RoCC response channel (Decoupled)
  output reg        resp_valid,
  input             resp_ready,
  output reg  [4:0] resp_rd,
  output reg [31:0] resp_data,

  // Busy while a command is in flight (for fences / tracking).
  output reg        busy
);

  localparam S_IDLE  = 2'd0;
  localparam S_BUSY  = 2'd1;
  localparam S_RESP  = 2'd2;

  function automatic [31:0] xsil_clz;
    input [31:0] a;
    integer i;
    reg found;
    begin
      xsil_clz = 32'd32;
      found = 1'b0;
      for (i = 31; i >= 0; i = i - 1) begin
        if (!found && a[i]) begin
          xsil_clz = 31 - i;
          found = 1'b1;
        end
      end
    end
  endfunction

{chr(10).join('  ' + l for l in decode_lines)}
  wire match_any = {matches_or};

  {match_q_regs}
  reg [31:0] rs1_q, rs2_q, rsd_q;
  reg [31:0] result_d;
  reg  [4:0] rd_q;
  reg  [1:0] state;

  always @* begin
    result_d = 32'd0;
    case (1'b1)
{chr(10).join(result_cases)}
      default: result_d = 32'd0;
    endcase
  end

  always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      state <= S_IDLE;
      cmd_ready <= 1'b0;
      resp_valid <= 1'b0;
      resp_rd <= 5'd0;
      resp_data <= 32'd0;
      busy <= 1'b0;
      rs1_q <= 32'd0;
      rs2_q <= 32'd0;
      rsd_q <= 32'd0;
      rd_q <= 5'd0;
      {match_q_clear}
    end else begin
      cmd_ready <= 1'b0;

      case (state)
        S_IDLE: begin
          resp_valid <= 1'b0;
          busy <= 1'b0;
          if (cmd_valid && match_any) begin
            cmd_ready <= 1'b1;
            {match_q_capture}
            rs1_q <= cmd_rs1;
            rs2_q <= cmd_rs2;
            rsd_q <= cmd_rsd;
            rd_q <= cmd_inst[11:7];
            busy <= 1'b1;
            state <= S_BUSY;
          end
          // Unrecognized opcodes: leave cmd_ready low so the BFM times out /
          // the core can treat as illegal — we do not accept them.
        end

        S_BUSY: begin
          busy <= 1'b1;
          // One compute cycle with stable latched operands.
          state <= S_RESP;
        end

        S_RESP: begin
          busy <= 1'b1;
          resp_valid <= 1'b1;
          resp_rd <= rd_q;
          resp_data <= result_d;
          if (resp_valid && resp_ready) begin
            resp_valid <= 1'b0;
            busy <= 1'b0;
            {match_q_clear}
            state <= S_IDLE;
          end
        end

        default: state <= S_IDLE;
      endcase
    end
  end

endmodule
"""


def write_module(path: Path, instructions: Iterable[Instruction], module: str = "xsil_rocc") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_module(list(instructions), module=module), encoding="utf-8")
    return path
