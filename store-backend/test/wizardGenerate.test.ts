import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { describe, it, expect } from 'vitest';

import { generateXsilSkeleton, WizardInputError } from '../src/lib/wizardGenerate';
import {
  computePayloadHashFromDir,
  validatePublishedXsilBuffer,
} from '../src/lib/xsilPublishValidate';

function extractToTmp(buffer: Buffer): string {
  const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'wizard-test-'));
  const tarball = path.join(tmpRoot, 'pkg.xsil');
  const extractDir = path.join(tmpRoot, 'extract');
  fs.mkdirSync(extractDir, { recursive: true });
  fs.writeFileSync(tarball, buffer);
  execFileSync('tar', ['-xzf', tarball, '-C', extractDir]);
  return extractDir;
}

/** Minimum-viable input for the canonical wizard generator. */
const REPO = 'https://github.com/tester/wizard-tests';
const STATUS = 'custom' as const;
const AUTHORITY = 'Wizard Test Authority';

describe('generateXsilSkeleton', () => {
  it('produces a valid .xsil that passes the publish-time validator', async () => {
    const r = await generateXsilSkeleton({
      name: 'my-ext',
      description: 'A demo extension generated by the wizard tests.',
      author: 'tester',
      isa: 'RV64GC',
      version: '0.1.0',
      repository: REPO,
      standardStatus: STATUS,
      authority: AUTHORITY,
      instructions: [
        {
          mnemonic: 'x.add',
          format: 'R',
          opcode: 'custom-0',
          funct3: '0b000',
          funct7: '0b0000000',
          operands: ['rd', 'rs1', 'rs2'],
          summary: 'rd = rs1 + rs2',
        },
      ],
      // Legacy target flags are ignored: the definition Wizard cannot assert support.
      targets: { qemu: true, binutils: true, llvm: true },
    });

    expect(r.filename).toBe('my-ext-0.1.0.xsil');
    expect(r.payloadChecksum).toMatch(/^sha256:[0-9a-f]{64}$/);

    const result = validatePublishedXsilBuffer(r.buffer, {
      slug: 'my-ext',
      formVersion: '0.1.0',
    });
    expect(result.checksumPayloadStored).toBe(r.payloadChecksum);
  });

  it('declared payload checksum matches recomputed hash from extracted dir', async () => {
    const r = await generateXsilSkeleton({
      name: 'demo-ext',
      description: 'Hash-consistency check.',
      repository: REPO,
      standardStatus: STATUS,
      authority: AUTHORITY,
    });

    const dir = extractToTmp(r.buffer);
    try {
      const computed = computePayloadHashFromDir(dir);
      expect(`sha256:${computed}`).toBe(r.payloadChecksum);

      const manifest = JSON.parse(
        fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'),
      );
      expect(manifest.checksums.payload).toBe(r.payloadChecksum);
      expect(manifest.payloadSize).toBeGreaterThan(0);
      expect(manifest.entry).toBeUndefined();
      expect(manifest.testEntry).toBeUndefined();
      expect(manifest.toolchain).toBeUndefined();
      expect(manifest.targets).toBeUndefined();
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  it('contains all expected files in the archive', async () => {
    const r = await generateXsilSkeleton({
      name: 'tree-ext',
      description: 'Make sure every wizard file is present.',
      repository: REPO,
      standardStatus: STATUS,
      authority: AUTHORITY,
      instructions: [
        { mnemonic: 'x.add', format: 'R', opcode: 'custom-0', funct3: '0b000', funct7: '0b0000000', operands: ['rd', 'rs1', 'rs2'], summary: 'rd = rs1 + rs2' },
      ],
    });
    const dir = extractToTmp(r.buffer);
    try {
      const expected = [
        'manifest.json',
        '.xsilignore',
        'README.md',
        'CHANGELOG.md',
        'LICENSE',
        'opcodes.json',
        'opcodes.h',
        'docs/overview.md',
        'examples/demo.S',
        'examples/x_add.S',
      ];
      for (const rel of expected) {
        const p = path.join(dir, rel);
        expect(fs.existsSync(p), `missing ${rel}`).toBe(true);
        expect(fs.statSync(p).size).toBeGreaterThan(0);
      }
      expect(fs.existsSync(path.join(dir, 'sim'))).toBe(false);
      expect(fs.existsSync(path.join(dir, 'tests'))).toBe(false);
      expect(fs.existsSync(path.join(dir, 'toolchain'))).toBe(false);
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  it('opcodes.h contains a __asm__ macro per declared instruction', async () => {
    const r = await generateXsilSkeleton({
      name: 'macro-ext',
      description: 'Headers expose .insn-based macros.',
      repository: REPO,
      standardStatus: STATUS,
      authority: AUTHORITY,
      instructions: [
        { mnemonic: 'x.alpha', format: 'R', opcode: 'custom-0', funct3: '0b001', funct7: '0b0000010', operands: ['rd', 'rs1', 'rs2'] },
        { mnemonic: 'x.beta',  format: 'I', opcode: 'custom-1', funct3: '0b010' },
      ],
    });
    const dir = extractToTmp(r.buffer);
    try {
      const header = fs.readFileSync(path.join(dir, 'opcodes.h'), 'utf8');
      expect(header).toMatch(/#define X_ALPHA\(rd, rs1, rs2\)/);
      expect(header).toMatch(/\.insn r 0x0b, 0x01, 0x02,/);
      expect(header).toMatch(/#define X_BETA\(rd, rs1, imm\)/);
      expect(header).toMatch(/\.insn i 0x2b, 0x02,/);
      // Header guard is derived from the slug.
      expect(header).toContain('#ifndef MACRO_EXT_OPCODES_H');
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  it('does not manufacture support metadata from legacy Wizard flags', async () => {
    const r = await generateXsilSkeleton({
      name: 'spike-ext',
      description: 'Definition-only archive check.',
      repository: REPO,
      standardStatus: STATUS,
      authority: AUTHORITY,
      instructions: [
        { mnemonic: 'x.add', format: 'R', opcode: 'custom-0', funct3: '0b000', funct7: '0b0000000', operands: ['rd', 'rs1', 'rs2'] },
      ],
      targets: { spike: true, qemu: true, binutils: true, llvm: true },
    });
    const dir = extractToTmp(r.buffer);
    try {
      const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
      expect(manifest.targets).toBeUndefined();
      expect(fs.existsSync(path.join(dir, 'sim'))).toBe(false);
      const readme = fs.readFileSync(path.join(dir, 'README.md'), 'utf8');
      expect(readme).toContain('does not include simulator, toolchain, RTL, or hardware artifacts');
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  it('LICENSE file matches the requested SPDX id', async () => {
    const r = await generateXsilSkeleton({
      name: 'mit-ext',
      description: 'MIT-licensed package.',
      repository: REPO,
      license: 'MIT',
      author: 'Felipe Pedroni',
      standardStatus: STATUS,
      authority: AUTHORITY,
    });
    const dir = extractToTmp(r.buffer);
    try {
      const lic = fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8');
      expect(lic.startsWith('MIT License')).toBe(true);
      expect(lic).toContain('Felipe Pedroni');
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  it('opcodes.json reflects user-provided instructions', async () => {
    const r = await generateXsilSkeleton({
      name: 'op-ext',
      description: 'Instructions land in opcodes.json.',
      repository: REPO,
      standardStatus: STATUS,
      authority: AUTHORITY,
      instructions: [
        { mnemonic: 'x.alpha', format: 'I', operands: ['rd', 'rs1', 'imm'] },
        { mnemonic: 'x.beta', format: 'R' },
      ],
    });
    const dir = extractToTmp(r.buffer);
    try {
      const opcodes = JSON.parse(fs.readFileSync(path.join(dir, 'opcodes.json'), 'utf8'));
      expect(opcodes.schemaVersion).toBe(1);
      expect(opcodes.instructions).toHaveLength(2);
      expect(opcodes.instructions[0].mnemonic).toBe('x.alpha');
      expect(opcodes.instructions[1].format).toBe('R');
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  it('does not invent a placeholder instruction when none is declared', async () => {
    const r = await generateXsilSkeleton({
      name: 'empty-opcodes',
      description: 'Definition with no instruction rows yet.',
      repository: REPO,
      standardStatus: STATUS,
      authority: AUTHORITY,
    });
    const dir = extractToTmp(r.buffer);
    try {
      const opcodes = JSON.parse(fs.readFileSync(path.join(dir, 'opcodes.json'), 'utf8'));
      expect(opcodes.instructions).toEqual([]);
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  it('rejects reserved slugs', async () => {
    await expect(
      generateXsilSkeleton({ name: 'extensilica', description: 'should fail', repository: REPO, standardStatus: STATUS, authority: AUTHORITY }),
    ).rejects.toBeInstanceOf(WizardInputError);
    await expect(
      generateXsilSkeleton({ name: 'admin', description: 'should fail', repository: REPO, standardStatus: STATUS, authority: AUTHORITY }),
    ).rejects.toBeInstanceOf(WizardInputError);
  });

  it('rejects invalid slug characters', async () => {
    await expect(
      generateXsilSkeleton({ name: 'Bad Name!', description: 'no spaces', repository: REPO, standardStatus: STATUS, authority: AUTHORITY }),
    ).rejects.toBeInstanceOf(WizardInputError);
  });

  it('rejects invalid semver version', async () => {
    await expect(
      generateXsilSkeleton({
        name: 'good-name',
        description: 'd',
        version: 'one.two.three',
        repository: REPO,
        standardStatus: STATUS,
        authority: AUTHORITY,
      }),
    ).rejects.toBeInstanceOf(WizardInputError);
  });

  it('rejects invalid instruction format', async () => {
    await expect(
      generateXsilSkeleton({
        name: 'good-name',
        description: 'd',
        repository: REPO,
        standardStatus: STATUS,
        authority: AUTHORITY,
        instructions: [
          // @ts-expect-error intentionally invalid
          { mnemonic: 'x.bad', format: 'Z' },
        ],
      }),
    ).rejects.toBeInstanceOf(WizardInputError);
  });

  it('requires a repository URL', async () => {
    await expect(
      // @ts-expect-error missing required fields on purpose
      generateXsilSkeleton({ name: 'good-name', description: 'no repo' }),
    ).rejects.toBeInstanceOf(WizardInputError);
  });

  it('rejects non-http(s) repository URLs', async () => {
    await expect(
      generateXsilSkeleton({
        name: 'good-name',
        description: 'bad scheme',
        repository: 'ftp://example.com/repo',
        standardStatus: STATUS,
        authority: AUTHORITY,
      }),
    ).rejects.toBeInstanceOf(WizardInputError);
  });

  it('persists repository in manifest.json', async () => {
    const r = await generateXsilSkeleton({
      name: 'with-repo',
      description: 'Has a repo url.',
      repository: 'https://gitlab.com/me/with-repo',
      standardStatus: STATUS,
      authority: AUTHORITY,
    });
    const dir = extractToTmp(r.buffer);
    try {
      const manifest = JSON.parse(
        fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'),
      );
      expect(manifest.repository).toBe('https://gitlab.com/me/with-repo');
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });

  it('requires standardStatus and authority', async () => {
    await expect(
      // @ts-expect-error missing standardStatus on purpose
      generateXsilSkeleton({
        name: 'good-name',
        description: 'd',
        repository: REPO,
        authority: AUTHORITY,
      }),
    ).rejects.toBeInstanceOf(WizardInputError);
    await expect(
      // @ts-expect-error missing authority on purpose
      generateXsilSkeleton({
        name: 'good-name',
        description: 'd',
        repository: REPO,
        standardStatus: STATUS,
      }),
    ).rejects.toBeInstanceOf(WizardInputError);
  });

  it('rejects unknown standardStatus values', async () => {
    await expect(
      generateXsilSkeleton({
        name: 'good-name',
        description: 'd',
        repository: REPO,
        // @ts-expect-error intentionally invalid status
        standardStatus: 'official',
        authority: AUTHORITY,
      }),
    ).rejects.toBeInstanceOf(WizardInputError);
  });

  it('persists standardStatus + authority in manifest.json', async () => {
    const r = await generateXsilSkeleton({
      name: 'classed-ext',
      description: 'Honest classification surfaces in the manifest.',
      repository: REPO,
      standardStatus: 'ratified',
      authority: 'RISC-V International',
    });
    const dir = extractToTmp(r.buffer);
    try {
      const manifest = JSON.parse(
        fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'),
      );
      expect(manifest.standardStatus).toBe('ratified');
      expect(manifest.authority).toBe('RISC-V International');

      const readme = fs.readFileSync(path.join(dir, 'README.md'), 'utf8');
      expect(readme).toContain('**Standard status:** `ratified`');
      expect(readme).toContain('**Authority:** RISC-V International');
    } finally {
      fs.rmSync(path.dirname(dir), { recursive: true, force: true });
    }
  });
});
